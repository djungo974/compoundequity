const SUPPORTED_LANGS = ["fr", "en", "es", "de"];
const DEFAULT_LANG = "en";

function getLang() {
  const stored = localStorage.getItem("ce_lang_v2");
  if (stored && SUPPORTED_LANGS.includes(stored)) return stored;
  return DEFAULT_LANG;
}

function t(key, lang) {
  const dict = I18N[lang] || I18N[DEFAULT_LANG];
  return dict[key] !== undefined ? dict[key] : (I18N[DEFAULT_LANG][key] || key);
}

function applyLanguage(lang) {
  if (!SUPPORTED_LANGS.includes(lang)) lang = DEFAULT_LANG;
  document.documentElement.setAttribute("lang", lang);
  localStorage.setItem("ce_lang_v2", lang);

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"), lang);
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.getAttribute("data-i18n-html"), lang);
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph"), lang));
  });
  document.querySelectorAll(".lang-switch button").forEach((btn) => {
    btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
  });

  const titleKey = document.body.getAttribute("data-title-key");
  if (titleKey) document.title = t(titleKey, lang);

  document.dispatchEvent(new CustomEvent("ce:langchange", { detail: { lang } }));
}

function initLangSwitch() {
  document.querySelectorAll(".lang-switch button").forEach((btn) => {
    btn.addEventListener("click", () => applyLanguage(btn.getAttribute("data-lang")));
  });
  applyLanguage(getLang());
}

document.addEventListener("DOMContentLoaded", initLangSwitch);
